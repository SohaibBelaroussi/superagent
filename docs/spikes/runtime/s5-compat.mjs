import { Mastra } from '@mastra/core/mastra';
import { Agent } from '@mastra/core/agent';
import { LibSQLStore } from '@mastra/libsql';
import { z } from 'zod';
import { startFakeServer } from './fake-openai.mjs';
const srv = await startFakeServer();
const mastra = new Mastra({ storage: new LibSQLStore({ id: 'st', url: ':memory:' }), logger: false });
const agent = new Agent({ id: 'c', name: 'c', instructions: 'C', model: { providerId: 'local', modelId: 'plain-model', url: srv.url } });
mastra.addAgent(agent);
const schema = z.object({ answer: z.string(), note: z.string().optional() });
let r = await agent.generate('structured please', { structuredOutput: { schema } });
let b = srv.log.at(-1).body;
console.log('S1 object:', JSON.stringify(r.object), '| response_format:', JSON.stringify(b.response_format)?.slice(0, 260));
r = await agent.generate('structured non-strict', { structuredOutput: { schema }, providerOptions: { local: { strictJsonSchema: false } } });
b = srv.log.at(-1).body;
console.log('S2 strict after providerOptions.local.strictJsonSchema=false:', b.response_format?.json_schema?.strict);
r = await agent.generate('structured jsonPromptInjection', { structuredOutput: { schema, jsonPromptInjection: true } }).catch(e => ({ err: e.message }));
b = srv.log.at(-1).body;
console.log('S3 jsonPromptInjection -> response_format:', JSON.stringify(b.response_format), 'object:', JSON.stringify(r.object ?? r.err));
await agent.generate('passthrough', { providerOptions: { local: { chat_template_kwargs: { enable_thinking: false }, parallel_tool_calls: false, top_k: 20 }, openaiCompatible: { reasoningEffort: 'low' } } });
b = srv.log.at(-1).body;
console.log('S4 passthrough body keys:', Object.keys(b).join(','), '| chat_template_kwargs=', JSON.stringify(b.chat_template_kwargs), 'parallel_tool_calls=', b.parallel_tool_calls, 'reasoning_effort=', b.reasoning_effort);
await agent.generate('settings', { modelSettings: { temperature: 0.2, maxOutputTokens: 77, topK: 5 } });
b = srv.log.at(-1).body;
console.log('S5 modelSettings -> temperature', b.temperature, 'max_tokens', b.max_tokens, 'top_k', b.top_k);
srv.close(); process.exit(0);
